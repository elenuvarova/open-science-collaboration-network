import { useEffect, useState } from "react";
import { getBrief } from "../api";
import { track } from "../analytics";

function CopyButton({ text }) {
  const [copied, setCopied] = useState(false);
  function copy() {
    navigator.clipboard.writeText(text).then(() => {
      setCopied(true);
      track("brief_copied");
      setTimeout(() => setCopied(false), 2000);
    });
  }
  return (
    <button className="btn btn-secondary btn-sm" onClick={copy}>
      <span role="status" aria-live="polite">{copied ? "Copied!" : "Copy brief"}</span>
    </button>
  );
}

// Inline Markdown → React (no innerHTML): **bold** and *italic* only.
function inline(text, keyBase) {
  const out = [];
  const re = /(\*\*[^*]+\*\*|\*[^*\s][^*]*\*)/g;
  let last = 0, m, i = 0;
  while ((m = re.exec(text))) {
    if (m.index > last) out.push(text.slice(last, m.index));
    const tok = m[0];
    out.push(tok.startsWith("**")
      ? <strong key={`${keyBase}-${i++}`}>{tok.slice(2, -2)}</strong>
      : <em key={`${keyBase}-${i++}`}>{tok.slice(1, -1)}</em>);
    last = m.index + tok.length;
  }
  if (last < text.length) out.push(text.slice(last));
  return out;
}

// Block Markdown the brief models actually emit: ## / ### headings, - or * bullets
// (one nesting level), paragraphs. Tables are flattened to "a · b · c" lines and
// rules dropped, so an unexpected format still reads cleanly.
function BriefText({ text }) {
  const elements = [];
  let list = null;
  let key = 0;
  const flush = () => {
    if (list) { elements.push(<ul key={key++} className="brief-list">{list}</ul>); list = null; }
  };
  for (const raw of text.split("\n")) {
    const line = raw.replace(/\s+$/, "");
    const heading = line.match(/^\s*\**\s*(#{2,3})\s+(.+?)\**\s*$/);
    const bullet = line.match(/^(\s*)[-*•]\s+(.*)$/);
    if (heading) {
      flush();
      const Tag = heading[1].length === 2 ? "h2" : "h3";
      elements.push(<Tag key={key++} className="subhead brief-h">{inline(heading[2].replace(/\*\*/g, ""), key)}</Tag>);
    } else if (bullet) {
      list ??= [];
      list.push(<li key={key++} className={bullet[1].length >= 2 ? "brief-sub" : undefined}>{inline(bullet[2], key)}</li>);
    } else if (/^\s*\|?\s*:?-{3,}/.test(line) || /^\s*-{3,}\s*$/.test(line)) {
      continue; // table separator row or horizontal rule
    } else if (line.trim().startsWith("|")) {
      flush();
      const cells = line.split("|").map((c) => c.trim()).filter(Boolean);
      elements.push(<p key={key++} className="body-text brief-row">{inline(cells.join(" · "), key)}</p>);
    } else if (line.trim() === "") {
      flush();
    } else {
      flush();
      elements.push(<p key={key++} className="body-text brief-p">{inline(line.trim(), key)}</p>);
    }
  }
  flush();
  return <div className="brief-text">{elements}</div>;
}

export default function BriefView({ topicId }) {
  const [brief, setBrief] = useState(null);
  const [loading, setLoading] = useState(true);
  const [missing, setMissing] = useState(false);

  useEffect(() => {
    if (!topicId) return;
    setLoading(true);
    setMissing(false);
    getBrief(topicId)
      .then(setBrief)
      .catch(() => setMissing(true))
      .finally(() => setLoading(false));
  }, [topicId]);

  if (loading) {
    return (
      <div className="card" role="status" aria-live="polite">
        <span className="sr-only">Loading strategy brief…</span>
        <div className="skel" style={{ height: 12, width: "40%", marginBottom: "var(--sp-4)" }} />
        {Array.from({ length: 6 }).map((_, i) => (
          <div key={i} className="skel" style={{ height: 10, width: `${70 + (i % 3) * 10}%`, marginBottom: "var(--sp-2)" }} />
        ))}
      </div>
    );
  }

  if (missing) {
    return (
      <div className="card" role="status" aria-live="polite" style={{ textAlign: "center", padding: "var(--sp-8) var(--sp-6)" }}>
        <div style={{ fontSize: "var(--text-3xl)", marginBottom: "var(--sp-4)" }} aria-hidden="true">🤖</div>
        <div className="subhead" style={{ marginBottom: "var(--sp-2)" }}>
          The strategy brief isn’t ready yet
        </div>
        <div className="body-text" style={{ color: "var(--text-3)", maxWidth: 340, margin: "0 auto" }}>
          We haven’t generated an AI strategy brief for this topic yet. Check back shortly, or explore the partner shortlist and network map in the meantime.
        </div>
      </div>
    );
  }

  return (
    <div>
      <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", gap: "var(--sp-3)", marginBottom: "var(--sp-4)" }}>
        <p className="muted" style={{ margin: 0 }}>
          AI strategy brief · generated by {brief.model || "Groq"}
          {brief.generated_at && (
            <> · {new Date(brief.generated_at).toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric" })}</>
          )}
        </p>
        <CopyButton text={brief.text} />
      </div>

      <div className="card">
        <BriefText text={brief.text} />
      </div>
    </div>
  );
}
